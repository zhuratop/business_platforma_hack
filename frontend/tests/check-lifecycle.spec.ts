import {test,expect} from '@playwright/test';

test('new check can be connected immediately and deleted without leaving a selected reference',async({page,context})=>{
 test.setTimeout(30000);
 await context.request.post('/api/auth/login',{data:{username:'alice',password:'demo'}});
 await page.goto('/?tab=config');
 const configSelect=page.getByRole('combobox',{name:'Сохранённые конфигурации'});
 await expect(configSelect).toBeVisible();
 const configId=await configSelect.inputValue();
 const before=(await (await context.request.get('/api/configs')).json()).data.find((c:any)=>c.id===configId);
 await page.locator('.sidebar').getByRole('button',{name:'Python-процедуры',exact:true}).click();
 await page.getByRole('button',{name:'Новая проверка',exact:true}).last().click();
 const code=page.getByRole('textbox',{name:'Редактор Python',exact:true});
 const source=await code.inputValue();
 expect(source).toMatch(/'id': 'my_changes_[a-f0-9]{16}'/);
 const name='Новая проверка '+Date.now()+'.py';
 await page.getByRole('textbox',{name:'Название',exact:true}).fill(name);
 await page.getByRole('button',{name:'Использовать в конфигурации',exact:true}).click();
 await expect(page.getByText('Проверка сохранена и подключена к конфигурации.',{exact:true})).toBeVisible();
 const row=page.locator('.check-options label').filter({hasText:name});
 await expect(row.getByRole('checkbox')).toBeEnabled();
 await expect(row.getByRole('checkbox')).toBeChecked();
 const boot=(await (await context.request.get('/api/bootstrap')).json()).data;
 const added=boot.scripts.find((s:any)=>s.name===name);expect(added).toBeTruthy();
 const config=boot.configs.find((c:any)=>c.id===configId);
 expect(config.checks).toContain(added.id);
 expect(config.checks).toEqual(expect.arrayContaining(before.checks));
 page.once('dialog',dialog=>dialog.dismiss());
 await row.getByRole('button',{name:'Удалить проверку',exact:true}).click();
 await expect(row).toBeVisible();
 page.once('dialog',dialog=>dialog.accept());
 await row.getByRole('button',{name:'Удалить проверку',exact:true}).click();
 await expect(row).toHaveCount(0);
 const after=(await (await context.request.get('/api/bootstrap')).json()).data;
 expect(after.scripts.some((s:any)=>s.id===added.id)).toBeFalsy();
 expect(after.configs.find((c:any)=>c.id===configId).checks).toEqual(before.checks);
 await page.reload();
 await expect(page.locator('.check-options label').filter({hasText:name})).toHaveCount(0);
});
