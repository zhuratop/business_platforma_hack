 if(process.env.SPR_E2E_RUN){await page.getByRole('button',{name:'Сохранить конфигурацию',exact:true}).click();await expect(page.locator('.notice')).toContainText('Конфигурация сохранена');await page.goto('/?run='+process.env.SPR_E2E_RUN+'&tab=journal')}
 else{await page.getByRole('button',{name:'Сохранить и запустить',exact:true}).click()}
 await expect(page.getByRole('heading',{name:'Журнал',exact:true})).toBeVisible();
 const runId=new URL(page.url()).searchParams.get('run');expect(runId).toBeTruthy();
 fs.writeFileSync('../runtime/browser-latest-run.txt',runId!);
 const other=await browser.newContext();
 const bob=await other.newPage();await bob.goto('/');
 await bob.getByLabel('Пользователь',{exact:true}).fill('bob');await bob.getByLabel('Пароль',{exact:true}).fill('demo');
 await bob.getByRole('button',{name:'Войти в рабочую область'}).click();
 await expect(bob.getByRole('heading',{name:'Датасеты',exact:true})).toBeVisible();
 expect((await other.request.get('/api/runs/'+runId)).status()).toBe(404);
 await expect(page.getByRole('button',{name:'Открыть результат',exact:true})).toBeVisible({timeout:300000});
 const codeButton=page.getByRole('button',{name:'Код',exact:true});await codeButton.first().click();
 await expect(page.getByRole('heading',{name:'Исполнявшийся код · normalize.py'})).toBeVisible();
 await expect(page.locator('.snapshot-code')).toContainText('def normalize');
 await page.getByRole('button',{name:'Закрыть код',exact:true}).click();
 await page.getByRole('button',{name:'Открыть результат',exact:true}).click();
 await expect(page.locator('.stat-grid')).toBeVisible();
 await expect(page.locator('[data-chart="decisions"]')).toBeVisible();
 await page.screenshot({path:'../runtime/overview.png',fullPage:true});
 await page.getByRole('button',{name:'Сводная таблица',exact:true}).click();
 await expect(page.locator('.attribute-tree')).toBeVisible();
