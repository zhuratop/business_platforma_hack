 await page.getByRole('button',{name:'Войти в рабочую область'}).click();
 await expect(page.getByRole('heading',{name:'Датасеты',exact:true})).toBeVisible();
 if(!process.env.SPR_E2E_RUN){
 await page.getByRole('button',{name:'Импортировать каталог',exact:true}).click();
 await expect(page.locator('.notice')).toContainText('пар JSON',{timeout:180000});
 }
 await page.getByRole('button',{name:'Конфигурация',exact:true}).click();
 for(const box of await page.getByRole('checkbox').all())await box.uncheck();
 for(const name of ['check_ar_drop_by_product.py','check_attribute_new_loss.py','check_external_score_drift.py','check_stop_factor_disappeared.py','check_target_model_changed.py'])await page.getByRole('checkbox',{name:name+' .py файл',exact:true}).check();
