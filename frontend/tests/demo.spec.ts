 await page.getByRole('button',{name:'Выбрать в конфигурации',exact:true}).click();
 await page.getByRole('checkbox',{name:checkName+' код редактора',exact:true}).check();
 await page.getByRole('button',{name:'Сохранить конфигурацию',exact:true}).click();
 await page.getByRole('button',{name:'Автопроверки',exact:true}).click();
