import {test,expect} from '@playwright/test';
import fs from 'node:fs';

test('full attribute tree folds descendants, filters slices/diffs and drills to exact attributes',async({page,context,browser})=>{
 test.setTimeout(30000);
 const run=fs.readFileSync('../runtime/browser-latest-run.txt','utf8').trim();
 await context.request.post('/api/auth/login',{data:{username:'alice',password:'demo'}});
 const root=(await (await context.request.post('/api/runs/'+run+'/pivot/tree',{data:{}})).json()).data;
 await page.goto('/?run='+run+'&tab=pivot');
 await expect(page.getByRole('heading',{name:'Сводная таблица',exact:true,level:1})).toBeVisible();
 await expect(page.getByRole('combobox',{name:'Представление сводной'})).toHaveCount(0);
 await expect(page.locator('.report-preset-row')).toHaveCount(0);
 const tree=page.locator('.attribute-tree');
 await expect(tree.locator('tbody tr[data-kind="path"]')).toHaveCount(root.nodes.length);
 const decisionRoot=tree.locator('tr[data-path="decisionResult"][data-kind="path"]');
 await decisionRoot.getByRole('button',{name:'Раскрыть decisionResult',exact:true}).click();
 const decision=tree.locator('tr[data-path="decisionResult.decision"][data-kind="path"]');
 await decision.getByRole('button',{name:'Раскрыть decision',exact:true}).click();
 await expect(tree.locator('tr[data-kind="value"]')).toHaveCount(2);
 await decisionRoot.getByRole('button',{name:'Свернуть decisionResult',exact:true}).click();
 await expect(tree.locator('tr[data-kind="value"]')).toHaveCount(0);await expect(decision).toHaveCount(0);
 await decisionRoot.getByRole('button',{name:'Раскрыть decisionResult',exact:true}).click();
 await expect(decision).toBeVisible();await expect(tree.locator('tr[data-kind="value"]')).toHaveCount(0);
 await page.getByRole('combobox',{name:'Дерево: срез'}).selectOption('AFTER');
 await page.getByRole('combobox',{name:'Дерево: DIFF_FLAG'}).selectOption('1');
 const filtered=(await (await context.request.post('/api/runs/'+run+'/pivot/tree',{data:{filters:{SOURCE:['AFTER'],DIFF_FLAG:[1]}}})).json()).data;
 await expect(tree.locator('tfoot td').last()).toContainText(filtered.totals.TOTAL.count.toLocaleString('ru-RU'));
 await expect(tree.getByRole('columnheader',{name:'BEFORE (MASTER)',exact:true})).toHaveCount(0);
 await expect(tree.getByRole('columnheader',{name:'AFTER (BETA)',exact:true})).toBeVisible();
 await decisionRoot.getByRole('button',{name:'Раскрыть decisionResult',exact:true}).click();
 await decision.getByRole('button',{name:'Раскрыть decision',exact:true}).click();
 const values=(await (await context.request.post('/api/runs/'+run+'/pivot/tree',{data:{path:'decisionResult.decision',stage:'values',array_key:'',filters:{SOURCE:['AFTER'],DIFF_FLAG:[1]}}})).json()).data;
 const approve=values.nodes.find((n:any)=>n.label==='"APPROVE"');
 const row=tree.locator('tr[data-kind="value"]').filter({hasText:'"APPROVE"'});
 await row.locator('.tree-number button').first().click();
 await expect(page.locator('.drawer h2')).toContainText(approve.cells.AFTER.count.toLocaleString('ru-RU'));
 await page.locator('.app-list button').first().click();
 await expect(page.locator('.highlight-row')).toHaveCount(1);await expect(page.locator('.highlight-row')).toContainText('decisionResult.decision');
 await page.getByRole('button',{name:'Закрыть заявку',exact:true}).click();await page.getByRole('button',{name:'Закрыть заявки',exact:true}).click();
 await tree.screenshot({path:'../runtime/attribute-tree.png'});
 await page.getByRole('combobox',{name:'Дерево: срез'}).selectOption('');await page.getByRole('combobox',{name:'Дерево: DIFF_FLAG'}).selectOption('');
 await tree.getByRole('button',{name:'Раскрыть appData',exact:true}).click();
 const id=tree.locator('tr[data-path="appData.application_id"][data-kind="path"]');
 await id.getByRole('button',{name:'Раскрыть application_id',exact:true}).click();
 await expect(tree.locator('tr[data-kind="value"]')).toHaveCount(50);
 await tree.getByRole('button',{name:/Показать ещё узлы/}).click();
 await expect(tree.locator('tr[data-kind="value"]')).toHaveCount(100);
 await tree.getByRole('button',{name:'Свернуть всё',exact:true}).click();await expect(tree.locator('tr[data-kind="value"]')).toHaveCount(0);
 await expect(page.locator('.compact-strategy-table')).toHaveCount(0);
 await page.reload();await expect(page.locator('.attribute-tree')).toBeVisible();
 await expect(page.getByRole('combobox',{name:'Представление сводной'})).toHaveCount(0);
 const other=await browser.newContext();await other.request.post('/api/auth/login',{data:{username:'bob',password:'demo'}});
 expect((await other.request.post('/api/runs/'+run+'/pivot/tree',{data:{}})).status()).toBe(404);await other.close();
});
