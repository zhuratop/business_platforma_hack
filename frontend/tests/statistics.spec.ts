import {test,expect} from '@playwright/test';
import fs from 'node:fs';

test('statistics use names, readable percentages and compact p-values',async({page,context})=>{
 test.setTimeout(30000);
 const run=fs.readFileSync('../runtime/browser-latest-run.txt','utf8').trim();
 await context.request.post('/api/auth/login',{data:{username:'alice',password:'demo'}});
 const response=await context.request.get('/api/runs/'+run+'/stats');
 expect(response.ok()).toBeTruthy();
 const payload=await response.json();
 const row={group:'123',group_name:'Продукт для проверки',name_available:true,n:100,before:50,after:40,delta:-.1,ci:[-.12345678,-.01234567],p:.123456789,p_adjusted:1.254165e-16,information:'available'};
 payload.data.families={products:[row],partners:[{...row,group:'456',group_name:'Партнёр для проверки'}]};
 await page.route('**/api/runs/'+run+'/stats',r=>r.fulfill({json:payload}));
 await page.goto('/?run='+run+'&tab=stats');
 await expect(page.locator('.stats-family-table')).toHaveCount(1);
 await expect(page.locator('.stats-family-table thead')).toContainText('Продукт (компания)');
 await expect(page.locator('.statistics-page')).not.toContainText('Медиана дельт');
 await expect(page.locator('.statistics-page')).not.toContainText('Оценка готовности стратегии');
 await expect(page.locator('.statistics-page')).not.toContainText('Целевая модель не менялась');
 const approval=page.locator('.stat-grid .stat').first();
 const metric=payload.data.app_approval_rate;
 await expect(approval.locator('b').first()).toHaveText((metric.delta>0?'+':'')+Number((metric.delta*100).toFixed(4))+' п.п.');
 await expect(approval.locator('.stat-ci')).toContainText(Number((metric.ci[0]*100).toFixed(4))+' п.п.');
 await expect(approval.locator('.stat-before-after')).toContainText(Number((metric.baseline.before*100).toFixed(4))+'%');
 await expect(approval.locator('.stat-before-after')).not.toContainText('п.п.');
 await expect(page.locator('.stat-grid .stat').nth(2).locator('h3')).toHaveText('Вероятность одобрения');
 await expect(page.locator('.statistics-page')).not.toContainText('Анализ сопоставимости');
 await expect(page.locator('.statistics-page')).not.toContainText('Внешний скор не менялся');
 const first=page.locator('.stats-family-table').first().locator('tbody tr');
 await expect(first.locator('td').first()).toContainText('Продукт для проверки');
 await expect(first.locator('td').first()).not.toContainText('123');
 await expect(first.locator('td').nth(4)).toHaveText('-10 п.п.');
 await expect(first.locator('td').nth(5)).toHaveText('-12.3457 п.п. … -1.2346 п.п.');
 await expect(first.locator('td').nth(2)).toContainText('50%');
 await expect(first.locator('td').nth(3)).toContainText('40%');
 await expect(page.locator('.stats-family-table').first().locator('thead')).toContainText('Разница, п.п.');
 await expect(page.locator('.stats-family-table').first().locator('thead')).toContainText('CI 95%, п.п.');
 await expect(first.locator('td').nth(6)).toHaveText('0.1235');
 await expect(first.locator('td').nth(7)).toHaveText('1.254e-16');
 await expect(page.locator('.statistics-page')).not.toContainText('Партнёр для проверки');
 await expect(page.locator('.stat-grid .stat').nth(1).locator('.stat-unit')).toContainText('продукта / заявку');
 await expect(page.locator('.stat-grid .stat').nth(1).locator('b').first()).not.toContainText('%');
});
